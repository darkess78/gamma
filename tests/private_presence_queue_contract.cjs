'use strict';
const assert = require('node:assert/strict');
const { PlaybackQueue } = require('../src/gamma/dashboard/static/presence_queue.js');
const item = (id, generation=1, epoch=1) => ({id,generation,epoch});
const q=new PlaybackQueue(2);
assert.deepEqual(q.sync(1,1),[]);
assert.equal(q.offer(item('a')),true);
assert.equal(q.offer(item('a')),false);
assert.equal(q.offer(item('b')),true);
assert.equal(q.offer(item('c')),false);
assert.equal(q.start().id,'a');
assert.equal(q.start(),null);
assert.equal(q.finish('b'),false);
assert.equal(q.finish('a'),true);
assert.equal(q.offer(item('c')),true);
assert.equal(q.start().id,'b');
assert.deepEqual(q.sync(2,1).map(x=>x.id),['b','c']);
assert.equal(q.finish('b'),false);
assert.equal(q.offer(item('old')),false);
assert.equal(q.offer(item('d',2)),true);
assert.equal(q.start().id,'d');
assert.deepEqual(q.clear().map(x=>x.id),['d']);
assert.equal(q.offer(item('d',2)),false);
assert.deepEqual(q.sync(2,1),[]);
assert.equal(q.offer(item('d',2)),false);
assert.deepEqual(q.sync(2,2),[]);
const original=item('d',2,2);
assert.equal(q.offer(original),true);
original.id='changed';original.generation=3;
assert.equal(q.start().id,'d');assert.equal(q.active.generation,2);
for(const values of [[0,1],[1,0],[NaN,1],[1,1.2],[true,1],[-1,1]])assert.throws(()=>q.sync(...values));
for(const value of [0,65,1.5,NaN,true])assert.throws(()=>new PlaybackQueue(value));
assert.equal(q.offer({id:'',generation:2,epoch:2}),false);
assert.equal(q.offer({id:'x'.repeat(129),generation:2,epoch:2}),false);
const bound=new PlaybackQueue(1);bound.sync(1,1);
for(let i=0;i<1024;i++){assert.equal(bound.offer(item(String(i))),true);assert.equal(bound.start().id,String(i));assert.equal(bound.finish(String(i)),true);}
assert.equal(bound.offer(item('overflow')),false);bound.sync(2,1);assert.equal(bound.offer(item('new',2)),true);
const chunks=new PlaybackQueue(8);chunks.sync(1,1);
const chunk=(id,index,count=2,utterance='spoken-once')=>({...item(id),utterance_id:utterance,chunk_index:index,chunk_count:count,final_chunk:index===count-1});
assert.equal(chunks.offer(chunk('gap',1,2,'missing-first')),false);
assert.equal(chunks.offer(chunk('late-start',0,2,'missing-first')),false);
assert.equal(chunks.offer(chunk('part0',0)),true);
const wrongCount = new PlaybackQueue(8);wrongCount.sync(1,1);assert.equal(wrongCount.offer(chunk('start',0)),true);
assert.equal(wrongCount.offer(chunk('wrong-count',1,3)),false);
assert.equal(wrongCount.offer(chunk('late-correct-count',1)),false);
assert.equal(chunks.offer({...chunk('wrong-final',1),final_chunk:false}),false);
assert.equal(chunks.offer(chunk('part1',1)),true);
assert.equal(chunks.start().id,'part0');assert.equal(chunks.start(),null);
assert.equal(chunks.finish('part1'),false);assert.equal(chunks.finish('part0'),true);
assert.equal(chunks.start().id,'part1');assert.equal(chunks.finish('part1'),true);
assert.equal(chunks.offer(chunk('new-id-old-utterance',0)),false);
assert.equal(chunks.offer(chunk('future0',0,3,'cancelled-utterance')),true);
assert.deepEqual(chunks.clear().map(x=>x.id),['future0']);
assert.equal(chunks.offer(chunk('future1',1,3,'cancelled-utterance')),false);
assert.equal(chunks.offer({...item('partial'),chunk_index:0}),false);
console.log('private presence queue contract passed');
